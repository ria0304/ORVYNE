"""ar-vr Integration Layer — Shared database setup.

SQLite for development; PostgreSQL configurable via DATABASE_URL env var.
Each project (BATISSE, WYA, TryOn, VELARIS) retains its own independent
database. This module creates coordination tables for the
integration layer only — user profiles, room assignments, saved outfits, and saved designs.

All personal data (room geometries, wardrobe images, GLB models) remains
in each project's own database. This module only stores coordination metadata.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Generator

from sqlalchemy import create_engine, Column, String, DateTime, JSON, Integer, Text, Index, func, Boolean, Float
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import Session, sessionmaker
from sqlalchemy.orm import declarative_mixin

from .config import DATABASE_URL, DEBUG

# ── SQLAlchemy setup ─────────────────────────────────────────────────────────

engine = create_engine(
    DATABASE_URL,
    echo=DEBUG,
    future=True,
)

SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine, future=True)

Base = declarative_base()

# ── Integration metadata model ────────────────────────────────────────────────

@declarative_mixin
class BaseModelMixin:
    """Mixin providing common columns for all models."""

    id = Column(Integer, primary_key=True, index=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


class IntegrationMetadata(BaseModelMixin, Base):
    """Coordination metadata for the integration layer.

    Stores non-sensitive mapping data between user IDs across projects,
    room assignments, and asset references. No floor plan geometry or
    private wardrobe data is stored here — that remains in each project's
    own database.
    """

    __tablename__ = "integration_metadata"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String(255), unique=True, index=True, nullable=False)  # Central user identifier
    batisse_project_id = Column(Integer, nullable=True, index=True)  # Linked BATISSE project
    room_assignments = Column(JSON, nullable=True, default=dict)  # room_id → function mapping
    __tablename__ = "integration_metadata"

    __table_args__ = (
        Index("ix_metadata_user_id", "user_id"),
    )


# ── User persistence models ───────────────────────────────────────────────────

class Users(Base):
    """Central user profile — coordination only.

    Each project retains its own user database. This table stores only the
    central user identifier and project linkages.
    """

    __tablename__ = "users"

    id = Column(String(255), primary_key=True, index=True)
    username = Column(String(255), nullable=False, default='user_123')
    email = Column(String(255), nullable=True)
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        Index("ix_users_username", "username"),
    )


class RoomSaves(Base):
    """Saved room assignments per user.

    Stores which rooms a user has assigned/navigated to across BATISSE floor plans.
    No room geometry is stored here — only metadata references.
    """

    __tablename__ = "room_saves"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String(255), nullable=False, index=True)
    room_id = Column(String(255), nullable=False)
    room_name = Column(String(255), nullable=True)
    floor_plan_id = Column(String(255), nullable=True)
    glb_model_path = Column(String(500), nullable=True)
    scale = Column(Float, default=1.0)
    assigned_at = Column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = (
    )


class OutfitSaves(Base):
    """Saved outfits per user.

    Stores outfit configurations generated by TryOn or recommended by WYA.
    No garment images are stored here — only metadata and preferences.
    """

    __tablename__ = "outfit_saves"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String(255), nullable=False, index=True)
    outfit_name = Column(String(255), nullable=False)
    garment_type = Column(String(100), nullable=True)
    items_json = Column(Text, nullable=True)  # JSON list of item references
    rating = Column(Integer, nullable=True)  # User rating 1-5
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = ()


class DesignSaves(Base):
    """Saved jewellery designs per user.

    Stores VELARIS design generation parameters and results.
    No 3D mesh data is stored here — only metadata and user preferences.
    """

    __tablename__ = "design_saves"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String(255), nullable=False, index=True)
    design_id = Column(String(255), nullable=False)
    jewelry_type = Column(String(50), nullable=True)  # ring, necklace, bracelet, earrings
    gemstone = Column(String(50), nullable=True)
    metal = Column(String(50), nullable=True)
    carat = Column(Float, nullable=True)
    shape = Column(String(50), nullable=True)
    generated_at = Column(DateTime(timezone=True), server_default=func.now())
    times_generated = Column(Integer, default=1)

    __table_args__ = ()


# ── Luna state persistence ──────────────────────────────────────────────────

class LunaState(BaseModelMixin, Base):
    """Luna robot companion state persistence.

    Stores Luna following preferences, expressions, voice settings, battery,
    zone, and speech status per user account.
    """

    __tablename__ = "luna_state"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String(255), nullable=False, index=True)
    is_following = Column(Boolean, default=True)
    following_offset = Column(JSON, nullable=True, default=dict)  # {x, y, z}
    current_expression = Column(String(50), default="idle")  # idle, happy, thinking, walking, sleepy
    voice_volume = Column(Float, default=0.8)
    voice_muted = Column(Boolean, default=False)
    battery = Column(Integer, default=100)
    zone = Column(String(50), default="")
    interaction_status = Column(String(50), default="idle")  # idle, providing_help
    speech_active = Column(Boolean, default=False)
    speech_text = Column(String(500), default="")
    dismissible = Column(Boolean, default=True)
    last_seen = Column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = ()


class FurnitureSaves(BaseModelMixin, Base):
    """Saved furniture placements per user.

    Stores furniture placements, types, and positions.
    """

    __tablename__ = "furniture_saves"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String(255), nullable=False, index=True)
    furniture_id = Column(String(255), nullable=False)
    furniture_type = Column(String(100), nullable=False)
    room_id = Column(String(255), nullable=False)
    position_x = Column(Float, default=0)
    position_y = Column(Float, default=0)
    position_z = Column(Float, default=0)
    rotation_y = Column(Float, default=0)
    world_state = Column(JSON, nullable=True)  # Additional world configuration

    __table_args__ = ()


# ── Engine helpers ────────────────────────────────────────────────────────────

def init_db() -> None:
    """Initialize the database — create all tables if they don't exist."""
    Base.metadata.create_all(bind=engine)


def get_db_session() -> Session:
    """Get a new database session for the integration layer."""
    return SessionLocal()


def get_db() -> Generator[Session, None, None]:
    """Dependency injector that yields a DB session and ensures cleanup."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


def get_engine() -> Any:
    """Return the SQLAlchemy engine (for advanced usage)."""
    return engine