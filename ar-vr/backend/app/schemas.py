"""Shared Pydantic schemas for the ar-vr integration layer.

These schemas define common types used across all integration adapters:
- User references (cross-project user identification)
- Room metadata (from BATISSE geometry)
- Asset references (3D assets across projects)
"""

from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# User References — Cross-project user identification
# ---------------------------------------------------------------------------

UserId = str  # Opaque user identifier (UUID or project-specific ID)


class UserReference(BaseModel):
    """Minimal user reference shared across integration services."""
    user_id: UserId
    username: Optional[str] = None
    email: Optional[str] = None


# ---------------------------------------------------------------------------
# Room Metadata — From BATISSE geometry export
# ---------------------------------------------------------------------------

RoomFunction = Literal[
    "bedroom",
    "living_room",
    "kitchen",
    "bathroom",
    "dining_room",
    "storage",
    "spare_bedroom",
    "study",
    "balcony",
    "hallway",
    "other",
]


class RoomMetadata(BaseModel):
    """Room information as generated by BATISSE and shared with the integration layer."""
    room_id: str
    room_name: str
    room_function: RoomFunction = "other"
    polygon: list[list[float]]  # [x, y] coordinates in plan units
    area_sq_m: Optional[float] = None
    confidence: Optional[float] = None  # BATISSE detection confidence
    has_window: bool = False
    has_door: bool = False


class ScaleInfo(BaseModel):
    """Scale information from BATISSE geometry."""
    units: str  # "m", "cm", "mm", "ft", "in"
    meters_per_pixel: Optional[float] = None
    scale_source: Literal["ocr_dimension", "vector", "user_reference", "manual"] = "manual"
    scale_confidence: Optional[float] = None


# ---------------------------------------------------------------------------
# Asset References — 3D assets across projects
# ---------------------------------------------------------------------------

AssetType = Literal[
    "house",
    "furniture",
    "garment",
    "jewellery",
    "avatar",
    "environment",
]


class AssetReference(BaseModel):
    """Reference to a 3D asset managed across integration services."""
    asset_id: str
    asset_type: AssetType
    name: str
    description: Optional[str] = None
    glb_url: Optional[str] = None  # GLB/glTF file URL
    thumbnail_url: Optional[str] = None
    metadata: dict = Field(default_factory=dict)  # Project-specific metadata


# ---------------------------------------------------------------------------
# Integration Request/Response DTOs
# ---------------------------------------------------------------------------

class IntegrationHealth(BaseModel):
    """Health check response for the integration service."""
    status: str = "ok"
    version: str = "0.1.0"
    services: dict[str, str] = Field(
        default_factory=lambda: {
            "batisse": "unknown",
            "wya": "unknown",
            "tryon": "unknown",
            "velaris": "unknown",
        }
    )


class ErrorResponse(BaseModel):
    """Standard error response across all integration endpoints."""
    error: str
    detail: str
    code: str = "integration_error"


class RoomAssignment(BaseModel):
    """User-assigned function for a house room (can be modified by user)."""
    room_id: str
    room_name: str
    assigned_function: RoomFunction
    updated_at: str  # ISO timestamp